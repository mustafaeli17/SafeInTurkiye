import {cityPath} from '../../lib/publicRoutes';
import {localizePath} from '../../lib/searchLocales';
import type {PlanSlot} from './plan';

export function plannerHref(city: string, lang: string, date?: string) {
  const params = new URLSearchParams({view: 'plan'});
  if (date) params.set('day', date);
  return localizePath(cityPath(city) + '?' + params, lang);
}

